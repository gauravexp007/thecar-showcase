export const CARS = BRANDS.flatMap((brand) =>
  brand.models.map((model) => {
    const slug = `${brand.id}-${model.id}`;
    return {
      ...model,
      brandId: brand.id,
      brand: brand.name,
      tagline: brand.tagline,
      slug,
      colors: colorOptions(slug),
    };
  }),
);

const BY_SLUG = new Map(CARS.map((car) => [car.slug, car]));

export const getCar = (slug) => BY_SLUG.get(slug) || null;
export const carsOfBrand = (brandId) => CARS.filter((car) => car.brandId === brandId);
export const getBrand = (brandId) => BRANDS.find((brand) => brand.id === brandId) || null;
